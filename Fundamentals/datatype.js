// ==========================================
// DATA TYPES
// ==========================================

// Data Type:
// A data type tells us what kind of value we are working with.


// ==========================================
// 1. STRING
// ==========================================

// String:
// A string is text written inside quotes.

let name = "Nafiz";
let university = "AIUB";

console.log(name);
console.log(typeof name);

console.log(university);
console.log(typeof university);


// ==========================================
// 2. NUMBER
// ==========================================

// Number:
// A number is a numeric value.
// It can be an integer or a decimal number.

let age = 24;
let cgpa = 3.75;

console.log(age);
console.log(typeof age);

console.log(cgpa);
console.log(typeof cgpa);


// ==========================================
// 3. BOOLEAN
// ==========================================

// Boolean:
// A boolean has only two values: true or false.

let isStudent = true;
let isWorking = false;

console.log(isStudent);
console.log(typeof isStudent);

console.log(isWorking);
console.log(typeof isWorking);


// ==========================================
// 4. UNDEFINED
// ==========================================

// Undefined:
// A variable is undefined when no value is assigned to it.

let phoneNumber;

console.log(phoneNumber);
console.log(typeof phoneNumber);


// ==========================================
// 5. NULL
// ==========================================

// Null:
// Null means intentionally having no value.

let address = null;

console.log(address);
console.log(typeof address);