// Type Coercion:
// Type coercion is when JavaScript automatically changes
// a value from one data type to another.


// String + Number

console.log("10" + 5); // "105"


// String - Number

console.log("10" - 5); // 5


// String * Number

console.log("10" * 2); // 20


// String / Number

console.log("10" / 2); // 5


// Boolean + Number

console.log(true + 1);  // 2
console.log(false + 1); // 1


// Loose Equality

console.log(5 == "5");  // true


// Strict Equality

console.log(5 === "5"); // false